import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { ASSESSMENT_VERSION } from '../src/assets/screening/screening-core.js';
import { analyzePreliminaryText, emptyTabCompletions, beginTabRun, completeTabRun, restoreTabCompletions, normalizeScreeningLinks } from '../src/assets/screening/screening-session-v14.js';

assert.equal(analyzePreliminaryText('This unusual system has not yet been described.').suggestedClass, 'unknown');
assert.equal(analyzePreliminaryText('This is purely informational personal brainstorming.').suggestedClass, 'informational');
assert.equal(analyzePreliminaryText('This is not purely informational; it controls live vessel control.').suggestedClass, 'high');
assert.equal(analyzePreliminaryText('There is no collision. We are discussing personal brainstorming.').suggestedClass, 'informational');
assert.equal(analyzePreliminaryText('Втрата керування може спричинити зіткнення судна.').suggestedClass, 'high');
assert.equal(analyzePreliminaryText('The payroll production system handles customer data.').suggestedClass, 'enterprise');
assert.throws(() => analyzePreliminaryText('too short'), /insufficient/);
assert.throws(() => analyzePreliminaryText('x'.repeat(6001)), /limit/);
const privateText = 'SECRET_UNIQUE_SOURCE_947: payroll data for a production process';
const summary = analyzePreliminaryText(privateText);
assert.equal(summary.requiresConfirmation, true);
assert.equal(summary.source, 'unverified-text-cues');
assert.ok(!JSON.stringify(summary).includes('SECRET_UNIQUE_SOURCE_947'));
assert.ok(!('answers' in summary) && !('evidenceStatus' in summary));
assert.ok(!summary.cueGroups.includes('critical'), 'Critical is never collapsed into an automatic lower class');

const result = { consequenceClass: 'critical', outcome: 'indeterminate', version: ASSESSMENT_VERSION };
const at = '2026-10-22T18:00:00.000Z';
let stats = beginTabRun(emptyTabCompletions(), 'run1');
stats = completeTabRun(stats, result, at);
assert.equal(stats.count, 1);
assert.equal(stats.last.consequenceClass, 'critical');
assert.deepEqual(completeTabRun(stats, result, '2026-10-22T18:01:00.000Z'), stats, 'same completed run must not count twice');
assert.deepEqual(restoreTabCompletions(JSON.parse(JSON.stringify(stats))), stats, 'reload preserves count and original result time');
stats = beginTabRun(stats, 'run2');
stats = completeTabRun(stats, { ...result, consequenceClass: 'unknown' }, '2026-10-22T18:02:00.000Z');
assert.equal(stats.count, 2);
assert.equal(stats.last.consequenceClass, 'unknown');
assert.equal(restoreTabCompletions({ ...stats, count: -1 }).count, 0);
assert.equal(restoreTabCompletions({ ...stats, count: 1.5 }).count, 0);
assert.equal(restoreTabCompletions({ ...stats, last: { ...stats.last, consequenceClass: 'higher' } }).count, 0, 'private enum is not silently accepted');
assert.equal(restoreTabCompletions({ ...stats, last: { ...stats.last, coreVersion: 'future-core' } }).count, 0);
assert.deepEqual(emptyTabCompletions(), { schema: 'goto-calm:screening-tab-completions:0.1', count: 0, activeRun: null, completedRun: null, last: null });
const source = await readFile(new URL('../src/assets/screening/screening-v14.js', import.meta.url), 'utf8');
assert.ok(source.includes('short section excerpts') && source.includes('короткі уривки розділів'), 'limited locally retained excerpts are disclosed in both languages');
assert.deepEqual(normalizeScreeningLinks({}, 'ua'), { doctrineBase: '/doctrine-site-box', contactUrl: '/doctrine-site-box/ua/contact/', aggregateEnabled: true });
assert.deepEqual(normalizeScreeningLinks({ doctrineBase: 'https://gotocalmaidp.github.io/doctrine-site-box/', contactUrl: '/contact', aggregateMode: 'off' }), { doctrineBase: 'https://gotocalmaidp.github.io/doctrine-site-box', contactUrl: '/contact', aggregateEnabled: false });
assert.equal(normalizeScreeningLinks({ doctrineBase: 'javascript:alert(1)', contactUrl: '//attacker.invalid/path' }).contactUrl, '/doctrine-site-box/en/contact/');
assert.equal(normalizeScreeningLinks({ doctrineBase: 'https://username:password@example.test/x' }).doctrineBase, '/doctrine-site-box');
console.log('screening-session-v14: orientation, raw-text exclusion and tab completion oracles PASS');
